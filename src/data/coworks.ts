// Monday–Friday from `open` to `close`, optional Saturday hours, closed on Sunday.
function schedule(open: number, close: number, saturday?: [number, number]): OpeningHours {
  const weekday = { open, close }
  return {
    0: null,
    1: weekday,
    2: weekday,
    3: weekday,
    4: weekday,
    5: weekday,
    6: saturday ? { open: saturday[0], close: saturday[1] } : null,
  }
}

